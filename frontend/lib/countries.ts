export function flagEmoji(iso2: string): string {
  return iso2
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));
}

export function isValidNationalNumber(country: Country, digits: string): boolean {
  return country.lengths.includes(digits.length);
}

/** For UI hints, e.g. "Enter 10 digits" or "Enter 8-9 digits". */
export function lengthHint(country: Country): string {
  const { lengths } = country;
  if (lengths.length === 1) return `${lengths[0]} digits`;
  return `${Math.min(...lengths)}-${Math.max(...lengths)} digits`;
}
