/**
 * Every country, its calling code, and its national significant-number
 * length(s) (digits dialled *after* the country code) — used to validate
 * the phone field per-country instead of one generic "7+ digits" rule.
 *
 * Numbering plans aren't all fixed-length in reality (several countries
 * accept a short range depending on number type); where that's the case we
 * list every length that's actually in common use. India's is a single
 * fixed 10, per the assignment's requirement.
 */

export interface Country {
  name: string;
  iso2: string;
  dial: string;
  /** Expected digit count(s) of the number *after* the dial code. */
  lengths: number[];
}

function country(name: string, iso2: string, dial: string, lengths: number | number[]): Country {
  return { name, iso2, dial, lengths: Array.isArray(lengths) ? lengths : [lengths] };
}

